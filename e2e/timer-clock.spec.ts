import { expect, test } from '@playwright/test'

test('starting and resuming shows the first elapsed second promptly', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-14T10:00:00Z') })
  await page.goto('/')
  await page.getByRole('button', { name: 'Minimal', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Deep Work', exact: true }).click()
  await page.clock.pauseAt(new Date('2026-10-14T11:00:00Z'))
  const timer = page.getByRole('timer')
  await expect(timer).toHaveText('50:00')
  await page.clock.runFor(250)
  await page.getByRole('button', { name: 'Démarrer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
  await expect(timer).toHaveText('50:00')
  await page.clock.runFor(1_100)
  await expect(timer).toHaveText('49:59')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reprendre', exact: true })).toBeVisible()
  const paused = await timer.textContent()
  await page.clock.runFor(5_250)
  await page.getByRole('button', { name: 'Reprendre', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
  await expect(timer).toHaveText(paused!)
  await page.clock.runFor(1_100)
  await expect(timer).toHaveText('49:58')
})

test('save feedback is brief while notes remain saved after reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Enregistré dans ce navigateur', { exact: true })).toHaveCount(0)
  const notes = page.getByRole('textbox', { name: 'Bloc-notes', exact: true })
  await notes.fill('Une note conservée en silence.')
  await notes.press('Tab')
  await expect(page.getByRole('status').filter({ hasText: 'Enregistré ici' })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Enregistré ici' })).toHaveCount(0)
  await page.reload()
  await expect(notes).toHaveValue('Une note conservée en silence.')
})
